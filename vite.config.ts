/// <reference types="vitest/config" />
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

/** Every file under `dir`, as paths relative to it with forward slashes. */
function filesUnder(dir: string, root = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? filesUnder(join(dir, e.name), root)
      : [relative(root, join(dir, e.name)).split('\\').join('/')],
  );
}

/**
 * Emits sw.js, a service worker that caches every file of the build on install, so the app opens
 * and runs with no connection once it has been loaded. Everything is served from the cache first,
 * because a weak signal in the yard is worse than none: a request can hang instead of failing. A
 * new build changes the cache name, so its worker installs alongside and takes over once every
 * tab of the old version is closed.
 */
function offlineServiceWorker(): Plugin {
  let publicDir = '';
  return {
    name: 'patiopyro-offline',
    apply: 'build',
    // After Vite's own plugins, so the built index.html is in the bundle.
    enforce: 'post',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_, bundle) {
      const hash = createHash('sha256');
      const files: string[] = [];
      for (const [name, out] of Object.entries(bundle)) {
        files.push(name);
        hash.update(name).update(out.type === 'chunk' ? out.code : out.source);
      }
      for (const name of publicDir ? filesUnder(publicDir) : []) {
        files.push(name);
        hash.update(name).update(readFileSync(join(publicDir, name)));
      }
      // The page itself, whether or not it was in the bundle yet.
      const sorted = [...new Set([...files, 'index.html'])].sort();
      const cache = `patiopyro-${hash.digest('hex').slice(0, 12)}`;
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by the patiopyro-offline plugin in vite.config.ts.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(['./', ...sorted.map((f) => `./${f}`)], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('patiopyro-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // The app is one page: any navigation gets it. Vary is ignored because module scripts send an
  // Origin header the precache requests didn't, and the files don't differ by it.
  const opts = { ignoreSearch: true, ignoreVary: true };
  const cached = caches.match(req.mode === 'navigate' ? './index.html' : req, opts);
  event.respondWith(cached.then((hit) => hit || fetch(req)));
});
`,
      });
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), tailwindcss(), offlineServiceWorker()],
  // React Flow + React + Zod make up the main chunk; SheetJS is split out on demand.
  build: { chunkSizeWarningLimit: 800 },
  test: {
    include: ['src/**/*.test.ts'],
  },
});
